CTYPE = {"i": "uint32_t", "f": "float", "d": "double", "l": "uint64_t"}
RENAME = {"atof_d": None, "free_i": None, "usleep_i": None, "posix_memalign_x": "posix_memalign",
          "wcrtomb_x": "wcrtomb", "glLineWidth_if": None}
VOID_RET_GL = {"glCreateShader", "glCreateProgram", "glGetError", "glGetString", "glCheckFramebufferStatus",
               "glGetUniformLocation", "glGetAttribLocation", "glIsBuffer", "glIsEnabled", "glIsRenderbuffer"}


def main(out):
    L = ['// Generated by recomp/arm/gen_imports.py — do not edit.', '#include "rt.h"',
         '#pragma clang diagnostic ignored "-Wint-conversion"', '#pragma clang diagnostic ignored "-Wincompatible-pointer-types"',
         '#include <stdlib.h>', '#include <stdio.h>', '#include <math.h>', '#include <string.h>', '#include <strings.h>',
         '#include <ctype.h>', '#include <wctype.h>', '#include <wchar.h>', '#include <unistd.h>', '#include <sys/stat.h>',
         '#include <GLES2/gl2.h>', 'void sincos(double, double *, double *); void sincosf(float, float *, float *);',
         '// GL_DEBUG=1 in the environment: check glGetError after every GL call and log the first errors with the call name.',
         'int rt_gl_debug = -1;',
         'static void glchk(const char *n){ if (rt_gl_debug < 0) rt_gl_debug = getenv("GL_DEBUG") != 0; if (!rt_gl_debug) return; GLenum e = glGetError(); static int k; if (e && k++ < 40) fprintf(stderr, "[gl] %s -> error %x\\n", n, e); }',
         '#define GLCHK(n) glchk(n)', '']
    seen = set()
    for row in SIGS.strip().splitlines():
        sig, *names = row.split()
        ret, args = sig.split(":")
        for n0 in names:
            if n0 in RENAME and RENAME[n0] is None:
                continue
            n = RENAME.get(n0, n0)
            if n in seen:
                continue
            seen.add(n)
            w, call = 0, []
            for a in args:
                if a in "dl" and w % 2:
                    w += 1
                if a == "i": call.append(f"ARGW({w})"); w += 1
                elif a == "f": call.append(f"argf_w({w})"); w += 1
                elif a == "d": call.append(f"argd_w({w})"); w += 2
                elif a == "l": call.append(f"argl_w({w})"); w += 2
            c = f"{n}({', '.join(call)})"
            if n.startswith("gl") and n not in VOID_RET_GL:
                body = f"{c}; GLCHK(\"{n}\");"
            elif n == "frexp":
                body = f"retd(frexp(argd_w(0),(int*)P(ARGW(2))));"
            elif n == "modf":
                body = f"retd(modf(argd_w(0),(double*)P(ARGW(2))));"
            elif n == "frexpf":
                body = f"retf(frexpf(argf_w(0),(int*)P(ARGW(1))));"
            elif n == "sincos":
                body = "double s_,c_; sincos(argd_w(0),&s_,&c_); W64(ARGW(2),*(uint64_t*)&s_); W64(ARGW(3),*(uint64_t*)&c_);"
            elif n == "sincosf":
                body = "float s_,c_; sincosf(argf_w(0),&s_,&c_); WF32(ARGW(1),s_); WF32(ARGW(2),c_);"
            elif ret == "i":
                body = f"RET((uint32_t)(uintptr_t){c});"
            elif ret == "l":
                body = f"RET64((uint64_t){c});"
            elif ret == "f":
                body = f"retf((float){c});"
            elif ret == "d":
                body = f"retd((double){c});"
            else:
                body = f"{c};"
            L.append(f"void imp_{n}(void){{ {body} }}")
    # bionic/ARM EABI helpers whose argument order differs from the C functions
    L += [
        "void imp___aeabi_memcpy(void){ memcpy(ARGP(0),ARGP(1),ARGW(2)); }",
        "void imp___aeabi_memcpy4(void){ imp___aeabi_memcpy(); }", "void imp___aeabi_memcpy8(void){ imp___aeabi_memcpy(); }",
        "void imp___aeabi_memmove(void){ memmove(ARGP(0),ARGP(1),ARGW(2)); }",
        "void imp___aeabi_memmove4(void){ imp___aeabi_memmove(); }", "void imp___aeabi_memmove8(void){ imp___aeabi_memmove(); }",
        "void imp___aeabi_memset(void){ memset(ARGP(0),(int)ARGW(2),ARGW(1)); }",
        "void imp___aeabi_memset4(void){ imp___aeabi_memset(); }", "void imp___aeabi_memset8(void){ imp___aeabi_memset(); }",
        "void imp___aeabi_memclr(void){ memset(ARGP(0),0,ARGW(1)); }",
        "void imp___aeabi_memclr4(void){ imp___aeabi_memclr(); }", "void imp___aeabi_memclr8(void){ imp___aeabi_memclr(); }",
    ]
    open(out, "w").write("\n".join(L) + "\n")
    print(f"{len(seen)} wrappers -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
