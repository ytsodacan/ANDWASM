#!/usr/bin/env python3
"""Generate headless GLES2 stubs for the Node debug build (no WebGL there).
Usage: gen_glnull.py <path to GLES2/gl2.h> <out.c>"""
import re
import sys

src = open(sys.argv[1]).read()
protos = re.findall(r"GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(\w+)\s*\(([^)]*)\);", src)
L = ['// Generated by gen_glnull.py: headless GLES2 (no rendering) for the Node debug build.',
     '#define GL_GLEXT_PROTOTYPES 1', '#include <GLES2/gl2.h>', '#include <GLES2/gl2ext.h>', '#include <string.h>',
     'static GLuint next_id = 1;']
for ret, name, args in protos:
    args = args.strip()
    params = [] if args in ("", "void") else [a.strip() for a in args.split(",")]
    pn = []
    for k, a in enumerate(params):
        m = re.match(r"(.*?)(\w+)\s*$", a)
        pn.append(m.group(2) if m else f"a{k}")
    r = ret.strip()
    body = ""
    if name in ("glGetIntegerv", "glGetFloatv", "glGetBooleanv"):
        # plausible limits for every query (a 0 limit can feed divisions / container sizes)
        body = (f"if ({pn[1]}) {{ memset({pn[1]}, 0, 4 * sizeof *{pn[1]}); {pn[1]}[0] = 16; "
                f"if ({pn[0]} == GL_MAX_TEXTURE_SIZE || {pn[0]} == GL_MAX_RENDERBUFFER_SIZE) {pn[1]}[0] = 4096; "
                f"if ({pn[0]} == GL_MAX_VERTEX_UNIFORM_VECTORS || {pn[0]} == GL_MAX_FRAGMENT_UNIFORM_VECTORS) {pn[1]}[0] = 256; "
                f"if ({pn[0]} == GL_VIEWPORT) {{ {pn[1]}[0] = 0; {pn[1]}[1] = 0; {pn[1]}[2] = 720; {pn[1]}[3] = 1280; }} "
                f"if ({pn[0]} == GL_FRAMEBUFFER_BINDING || {pn[0]} == GL_RENDERBUFFER_BINDING || {pn[0]} == GL_ARRAY_BUFFER_BINDING || "
                f"{pn[0]} == GL_ELEMENT_ARRAY_BUFFER_BINDING || {pn[0]} == GL_TEXTURE_BINDING_2D || {pn[0]} == GL_CURRENT_PROGRAM) {pn[1]}[0] = 0; }}")
    elif name in ("glGetShaderiv", "glGetProgramiv"):
        body = f"if ({pn[2]}) *{pn[2]} = ({pn[1]} == GL_INFO_LOG_LENGTH) ? 0 : 1;"
    elif name.startswith("glGen") and len(pn) == 2:
        body = f"for (GLsizei i = 0; i < {pn[0]}; i++) {pn[1]}[i] = next_id++;"
    elif name == "glGetString":
        body = (f'return (const GLubyte *)({pn[0]} == GL_EXTENSIONS ? "GL_OES_vertex_array_object GL_OES_element_index_uint" : '
                f'{pn[0]} == GL_VERSION ? "OpenGL ES 2.0 (headless)" : "headless");')
    elif name == "glCheckFramebufferStatus":
        body = "return GL_FRAMEBUFFER_COMPLETE;"
    elif name in ("glCreateShader", "glCreateProgram"):
        body = "return next_id++;"
    elif r != "void":
        body = f"return ({r})0;"
    body += "".join(f" (void){p};" for p in pn)
    L.append(f"{r} {name}({args or 'void'}) {{ {body} }}")
L += ["void glGenVertexArraysOES(GLsizei n, GLuint *a) { for (GLsizei i = 0; i < n; i++) a[i] = next_id++; }",
      "void glBindVertexArrayOES(GLuint a) { (void)a; }",
      "void glDeleteVertexArraysOES(GLsizei n, const GLuint *a) { (void)n; (void)a; }",
      "GLboolean glIsVertexArrayOES(GLuint a) { return a != 0; }"]
open(sys.argv[2], "w").write("\n".join(L) + "\n")
print(len(protos), "stubs ->", sys.argv[2])
