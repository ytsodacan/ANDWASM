#!/usr/bin/env python3
"""One-command ANDWASM port of an armeabi-v7a Android game (APK, XAPK or APKM) to a browser build.

Usage: python3 recomp/arm/port_apk.py <game.apk|.xapk|.apkm> [--name NAME] [--work DIR]

- Unpacks the package; finds the base APK and the armeabi-v7a native library.
- Lifted libraries are cached by content hash under build/lib-<hash>: games that ship the same engine
  library (e.g. several Buildbox games) reuse one lifted + compiled build and only differ in their data.
- Engine profiles are applied automatically. Buildbox: SpiderMonkey JIT entry checks are stubbed (scripts run
  in the interpreter) and the on-screen joystick is hidden when hooks.c is present; the data.pkg password is
  read from the app's dex (PTJniHelper.password) into andwasm.cfg.
- Links build/games/<name>/web (index.html, index.js, index.wasm, index.data). Serve it with
  `python3 recomp/arm/web/serve.py build/games/<name>/web <port>` (threads need COOP/COEP headers).
"""
import argparse
import ast
import hashlib
import os
import shutil
import subprocess
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HERE = os.path.dirname(os.path.abspath(__file__))

BUILDBOX_STUBS = [
    "_ZN2js3jit24CanEnterBaselineAtBranchEP9JSContextPNS_16InterpreterFrameEb=1",
    "_ZN2js3jit22CanEnterBaselineMethodEP9JSContextRNS_8RunStateE=1",
    "_ZN2js3jit16CanEnterAtBranchEP9JSContextN2JS6HandleIP8JSScriptEEPNS0_13BaselineFrameEPh=1",
    "_ZN2js3jit8CanEnterEP9JSContextRNS_8RunStateE=1",
    "_ZN2js3jit23CanEnterUsingFastInvokeEP9JSContextN2JS6HandleIP8JSScriptEEj=1",
]
BUILDBOX_WRAPS = ["_ZN23PTPObjectButtonJoystick8setModelERKNSt6__ndk110shared_ptrI24PTModelObjectManipulatorEE"]
BUILDBOX_HOOKS = r'''// Buildbox hooks (generated by port_apk.py). Hide the on-screen joystick for keyboard play: its touch
// handler only tests the touch position, so it keeps working while invisible. SHOW_JOYSTICK=1 keeps it.
#include "rt.h"
#include "funcs.h"
#include <stdlib.h>
void hook_%(ADDR)s(void) {
  uint32_t self = g_r[0];
  F_%(ADDR)s_orig();
  static uint32_t set_visible;
  if (!set_visible) set_visible = rt_export("_ZN7cocos2d4Node10setVisibleEb");
  if (set_visible && self && !getenv("SHOW_JOYSTICK")) {
    uint32_t keep[2] = { g_r[0], g_r[1] };
    rt_call(set_visible, 2, self, 0u);
    g_r[0] = keep[0]; g_r[1] = keep[1];
  }
}
'''


def run(cmd, **kw):
    print("+", " ".join(cmd) if isinstance(cmd, list) else cmd, flush=True)
    subprocess.run(cmd, check=True, **kw)


def unpack(pkg, work):
    """Return (base_apk_path, assets_dir, lib_path, dex_paths) after unpacking into work/."""
    os.makedirs(work, exist_ok=True)
    apks = []
    with zipfile.ZipFile(pkg) as z:
        names = z.namelist()
        if any(n.endswith(".apk") for n in names):          # XAPK / APKM bundle
            for n in names:
                if n.endswith(".apk"):
                    out = os.path.join(work, "bundle", os.path.basename(n))
                    os.makedirs(os.path.dirname(out), exist_ok=True)
                    with z.open(n) as src, open(out, "wb") as dst:
                        shutil.copyfileobj(src, dst)
                    apks.append(out)
        else:
            apks.append(os.path.abspath(pkg))
    base = None
    for a in apks:
        with zipfile.ZipFile(a) as z:
            if "AndroidManifest.xml" in z.namelist() and any(n.startswith("classes") and n.endswith(".dex") for n in z.namelist()):
                base = a
    if base is None:
        sys.exit("no base APK (with classes.dex) found in the package")
    lib = None
    for a in apks:
        with zipfile.ZipFile(a) as z:
            sos = [i for i in z.infolist() if i.filename.startswith("lib/armeabi-v7a/") and i.filename.endswith(".so")]
            if sos:
                main = max(sos, key=lambda i: i.file_size)
                out = os.path.join(work, "lib", os.path.basename(main.filename))
                os.makedirs(os.path.dirname(out), exist_ok=True)
                with z.open(main) as src, open(out, "wb") as dst:
                    shutil.copyfileobj(src, dst)
                lib = out
    if lib is None:
        sys.exit("no armeabi-v7a native library in the package")
    base_dir = os.path.join(work, "base")
    with zipfile.ZipFile(base) as z:
        z.extractall(base_dir)
    dex = sorted(os.path.join(base_dir, n) for n in os.listdir(base_dir) if n.startswith("classes") and n.endswith(".dex"))
    return base, os.path.join(base_dir, "assets"), lib, dex


def buildbox_cfg(dex, out):
    """andwasm.cfg with the constant PTJniHelper.password returns (data.pkg key material)."""
    val = None
    for d in dex:
        r = subprocess.run([sys.executable, "-I", os.path.join(HERE, "dexmethod.py"), d, "Lcom/secrethq/utils/PTJniHelper;", "password"],
                           capture_output=True, text=True)
        for line in r.stdout.splitlines():
            if line.startswith("const-string "):
                val = ast.literal_eval(line.split(" ", 1)[1]); break
        if val is not None:
            break
    with open(out, "w") as f:
        f.write("# constants returned by the app's Java getters (extracted from its dex by port_apk.py)\n")
        if val is not None:
            f.write(f"PTJniHelper.password={val}\n")
    return val is not None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("package")
    ap.add_argument("--name")
    ap.add_argument("--work")
    a = ap.parse_args()
    name = a.name or os.path.splitext(os.path.basename(a.package))[0]
    games = os.path.join(ROOT, "build", "games", name)
    work = a.work or os.path.join(games, "unpacked")
    base_apk, assets, lib, dex = unpack(a.package, work)
    digest = hashlib.sha256(open(lib, "rb").read()).hexdigest()[:12]
    libname = os.path.splitext(os.path.basename(lib))[0]
    cache = os.path.join(ROOT, "build", f"lib-{digest}")
    buildbox = libname == "libBBRuntime"
    print(f"game {name}: library {os.path.basename(lib)} ({digest}){' [Buildbox]' if buildbox else ''}")

    cfg = os.path.join(games, "andwasm.cfg")
    os.makedirs(games, exist_ok=True)
    if buildbox:
        print("data.pkg password:", "found" if buildbox_cfg(dex, cfg) else "not found")
    else:
        open(cfg, "w").write("# no engine-specific constants\n")
    # package name (split bundles name the base APK after the package)
    pkgname = os.path.splitext(os.path.basename(base_apk))[0]
    if "." in pkgname and not pkgname.startswith("base"):
        with open(cfg, "a") as f:
            f.write(f"package={pkgname}\n")

    # Lift + compile once per distinct library
    if not os.path.exists(os.path.join(cache, "table.c")):
        args = [sys.executable, os.path.join(HERE, "build_arm.py"), lib, cache, "--name", libname]
        if buildbox:
            for s in BUILDBOX_STUBS: args += ["--stub", s]
            for w in BUILDBOX_WRAPS: args += ["--wrap", w]
        run(args, cwd=ROOT)
        if buildbox:
            from elftools.elf.elffile import ELFFile
            st = ELFFile(open(lib, "rb")).get_section_by_name(".symtab")
            addr = next((s["st_value"] & ~1 for s in st.iter_symbols() if s.name == BUILDBOX_WRAPS[0]), None) if st else None
            if addr:
                open(os.path.join(cache, "hooks.c"), "w").write(BUILDBOX_HOOKS % {"ADDR": f"{addr:X}"})
    else:
        print(f"reusing lifted library {cache}")

    web = os.path.join(games, "web")
    run(["make", "-f", "recomp/arm/Makefile", f"OUT={os.path.relpath(cache, ROOT)}", f"NAME={libname}",
         f"WEB={os.path.relpath(web, ROOT)}", f"ASSETS={assets}", f"APK={base_apk}", f"CFG={cfg}", f"-j{os.cpu_count() or 4}"], cwd=ROOT)
    print(f"\nDone: {web}\nServe: python3 recomp/arm/web/serve.py {os.path.relpath(web, ROOT)} 8656")


if __name__ == "__main__":
    main()
