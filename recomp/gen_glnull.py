#!/usr/bin/env python3
"""Generate runtime/gl_null.c: headless GLES2 stubs for the gl* imports of the recompiled library."""
import re, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import elf
so, hdr_path, out_path = sys.argv[1:4]
imps = [n for n in elf.load(so).imports if n.startswith("gl")]
hdr = open(hdr_path).read()
out = ['// Generated by gen_glnull.py: null GLES2 for headless (Node) runs.', '#include <GLES2/gl2.h>',
       'static GLuint next_id = 1; int gl_draw_calls;']
special = {
 'glGetError': 'return GL_NO_ERROR;', 'glCreateShader': 'return next_id++;', 'glCreateProgram': 'return next_id++;',
 'glCheckFramebufferStatus': 'return GL_FRAMEBUFFER_COMPLETE;', 'glGetUniformLocation': 'return (GLint)(next_id++);',
 'glGetString': 'switch(name){case GL_VENDOR:return (const GLubyte*)"WebRoyale";case GL_RENDERER:return (const GLubyte*)"null";'
                'case GL_VERSION:return (const GLubyte*)"OpenGL ES 2.0";default:return (const GLubyte*)"";}',
 'glGenBuffers': 'for(int i=0;i<n;i++) buffers[i]=next_id++;', 'glGenTextures': 'for(int i=0;i<n;i++) textures[i]=next_id++;',
 'glGenFramebuffers': 'for(int i=0;i<n;i++) framebuffers[i]=next_id++;',
 'glGetShaderiv': '*params=(pname==GL_INFO_LOG_LENGTH)?0:1;', 'glGetProgramiv': '*params=(pname==GL_INFO_LOG_LENGTH)?0:1;',
 'glGetIntegerv': '*data=(pname==GL_MAX_TEXTURE_SIZE)?4096:(pname==GL_MAX_VERTEX_ATTRIBS)?16:(pname==GL_FRAMEBUFFER_BINDING)?0:8;',
 'glGetShaderInfoLog': 'if(bufSize) infoLog[0]=0; if(length)*length=0;', 'glGetProgramInfoLog': 'if(bufSize) infoLog[0]=0; if(length)*length=0;',
 'glDrawArrays': 'gl_draw_calls++;', 'glDrawElements': 'gl_draw_calls++;',
}
for n in imps:
    m = re.search(r'GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+' + n + r'\s*\(([^)]*)\);', hdr)
    ret, args = m.group(1).strip(), m.group(2)
    out.append(f'{ret} {n}({args}){{ {special.get(n, "" if ret == "void" else "return 0;")} }}')
open(out_path, 'w').write('\n'.join(out) + '\n')
print(len(imps), 'gl stubs ->', out_path)
